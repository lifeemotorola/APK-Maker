// Optional real-browser checks. Install playwright + @sparticuz/chromium into
// .cache/store-browser, start serve.mjs, then run this file. API/APK responses
// below are TEST FIXTURES, never live releases or deliverable app binaries.
import assert from 'node:assert/strict';
import { readFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import path from 'node:path';
const root = fileURLToPath(new URL('../../../', import.meta.url));
const deps = process.env.BROWSER_DEPS || path.join(root, '.cache/store-browser/node_modules');
const { chromium } = await import(pathToFileURL(path.join(deps, 'playwright/index.mjs')));
const { default: headless } = await import(pathToFileURL(path.join(deps, '@sparticuz/chromium/build/index.js')));
const apps = JSON.parse(readFileSync(path.join(root, 'downloads/apps.json')));
const repo = 'https://github.com/lifeemotorola/APK-Maker';
const release = { tag_name: 'apk-downloads', draft: false, assets: apps.map((a, index) => ({ name: a.file, state: 'uploaded', size: (index + 1) * 1048576, label: `version=${a.version};sha256=${'a'.repeat(64)};commit=${'b'.repeat(40)}`, updated_at: `2026-10-${String(index + 1).padStart(2, '0')}T12:00:00Z`, browser_download_url: `${repo}/releases/download/apk-downloads/${a.file}` })) };
const { inflate } = await import(pathToFileURL(path.join(deps, '@sparticuz/chromium/build/lambdafs.js')));
const libraries = await inflate(path.join(deps, '@sparticuz/chromium/bin/al2023.tar.br'));
const browser = await chromium.launch({ executablePath: await headless.executablePath(), args: headless.args.filter(a => !['--disable-web-security', '--allow-running-insecure-content'].includes(a)), headless: true,
  env: { ...process.env, LD_LIBRARY_PATH: path.join(libraries, 'lib') + (process.env.LD_LIBRARY_PATH ? ':' + process.env.LD_LIBRARY_PATH : '') } });
const context = await browser.newContext({ viewport: { width: 1440, height: 1080 }, deviceScaleFactor: 1, acceptDownloads: true });
const page = await context.newPage(), errors = [];
page.on('pageerror', error => errors.push(error.message));
let mode = 'ready';
await context.route('https://api.github.com/**', route => route.fulfill({ status: mode === 'ready' ? 200 : mode === 'empty' ? 404 : 403, contentType: 'application/json', headers: { 'Access-Control-Allow-Origin': '*' }, body: JSON.stringify(mode === 'ready' ? release : { message: mode === 'empty' ? 'Not Found' : 'API rate limit exceeded' }) }));
await context.route(`${repo}/releases/download/**`, route => route.fulfill({ status: 200, headers: { 'Content-Type': 'application/vnd.android.package-archive', 'Content-Disposition': 'attachment; filename="ChoirTune.apk"' }, body: Buffer.from('TEST DOWNLOAD FIXTURE, NOT AN APK') }));
const base = process.env.SITE_URL || 'http://127.0.0.1:4173';
try {
  await page.goto(`${base}/APK-Maker/downloads/`);
  await page.waitForFunction(() => document.querySelectorAll('#app-grid a[data-download]').length === 10);
  assert.match(await page.title(), /APK-Maker/);
  assert.equal(await page.locator('.app-card').count(), 10);
  await page.locator('#filters [data-category="music"]').click();
  assert.equal(await page.locator('.app-card').count(), 4);
  await page.locator('#search').fill('piano');
  assert.equal(await page.locator('.app-card').count(), 1);
  assert.match(await page.locator('.card-title').innerText(), /KeySense/);
  await page.locator('#search').fill('nothing-exists-123');
  assert.equal(await page.locator('.app-card').count(), 0);
  assert.equal(await page.locator('#empty-state').isVisible(), true);
  await page.locator('#reset').click();
  await page.locator('[data-save="choirtune"]').click();
  await page.locator('#nav-saved').click();
  assert.equal(await page.locator('.app-card').count(), 1);
  await page.reload();
  await page.waitForFunction(() => document.querySelector('#saved-count').textContent === '1');
  assert.equal(await page.locator('.app-card').count(), 1);
  await page.locator('#nav-all').click();
  await page.locator('#sort').selectOption('name');
  assert.equal(await page.locator('.card-title').first().innerText(), 'Bible Quiz');
  await page.locator('#sort').selectOption('updated');
  assert.equal(await page.locator('.card-title').first().innerText(), 'Community Market');
  await page.locator('#sort').selectOption('size');
  assert.equal(await page.locator('.card-title').first().innerText(), 'Choir Tune Finder');
  await page.locator('[data-app="choirtune"] [data-detail]').first().click();
  assert.equal(await page.locator('#app-dialog').isVisible(), true);
  assert.match(await page.locator('#dialog-content').innerText(), /2.5 GB available RAM/);
  assert.equal(await page.locator('.hash').innerText(), 'a'.repeat(64));
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('#app-dialog').isVisible(), false);
  const downloadEvent = page.waitForEvent('download');
  await page.locator('[data-app="choirtune"] [data-download]').click();
  const download = await downloadEvent;
  assert.equal(download.suggestedFilename(), 'ChoirTune.apk');
  // Cross-origin fixture download completion is not reliable in this sandbox;
  // assert the native browser download event/filename, not completed APK bytes.
  await download.cancel().catch(() => {});
  await page.locator('#nav-all').click();
  await page.evaluate(() => window.scrollTo(0, 0));
  mkdirSync(path.join(root, '.cache/store-screenshots'), { recursive: true });
  await page.waitForTimeout(4600);
  await page.screenshot({ path: path.join(root, '.cache/store-screenshots/desktop.png'), fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: path.join(root, '.cache/store-screenshots/mobile.png'), fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.locator('#filters [data-category="faith"]').click();
  assert.equal(await page.locator('.app-card').count(), 2);
  await page.locator('[data-app="pastoral"] .details-button').click();
  assert.equal(await page.locator('#app-dialog').isVisible(), true);
  await page.locator('#close-dialog').click();
  mode = 'empty'; await page.reload();
  await page.waitForFunction(() => document.querySelector('#release-message').textContent.includes('not published yet'));
  assert.equal(await page.locator('a[data-download]').count(), 0);
  assert.ok(await page.locator('.download-button:disabled').count() > 0);
  mode = 'error'; await page.locator('#retry').click();
  await page.waitForFunction(() => document.querySelector('#release-message').textContent.includes('Could not check'));
  assert.equal(await page.locator('a[data-download]').count(), 0);
  mode = 'ready'; await page.locator('#retry').click();
  await page.waitForFunction(() => document.querySelectorAll('a[data-download]').length > 0);
  assert.deepEqual(errors, []);
  console.log('PASS browser: desktop/mobile layout, search, filters, saved persistence, sorting, details, direct download event/filename (fixture), release 404/rate-limit/retry; no page errors.');
} finally { await browser.close(); }
