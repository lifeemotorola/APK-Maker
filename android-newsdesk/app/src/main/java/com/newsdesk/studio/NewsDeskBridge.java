package com.newsdesk.studio;

import android.util.Base64;
import android.util.Log;
import android.webkit.JavascriptInterface;

import org.json.JSONArray;
import org.json.JSONObject;

import java.io.File;
import java.io.FileInputStream;
import java.io.FileOutputStream;
import java.security.MessageDigest;
import java.text.SimpleDateFormat;
import java.util.ArrayList;
import java.util.Collections;
import java.util.Comparator;
import java.util.Date;
import java.util.HashSet;
import java.util.List;
import java.util.Locale;
import java.util.Set;

/**
 * JavascriptInterface exposed to the WebView pages as `window.NewsDeskBridge`.
 * Backs the media library of the in-page shim (assets/www/__shim.js):
 *
 *   listUploads()            -> JSON array of {name,url,size,pretty,mtime,video}
 *                               (bundled demo media + user uploads, newest first)
 *   saveUpload(name,mime,b64)-> writes the file into filesDir/uploads with the
 *                               same naming + sha1-dedupe rules as server.py
 *   deleteUpload(url)        -> deletes a user upload; bundled demo files are
 *                               "deleted" via a persisted tombstone set
 */
public class NewsDeskBridge {

    private static final String[] VIDEO_EXTS = {".mp4", ".webm", ".m4v", ".mov", ".ogv"};
    private static final String[] IMG_EXTS = {".png", ".jpg", ".jpeg", ".webp", ".gif", ".svg"};

    private final MainActivity activity;

    public NewsDeskBridge(MainActivity activity) {
        this.activity = activity;
    }

    @JavascriptInterface
    public String platform() {
        return "android";
    }

    @JavascriptInterface
    public String appVersion() {
        try {
            return activity.getPackageManager()
                    .getPackageInfo(activity.getPackageName(), 0).versionName;
        } catch (Exception e) {
            return "1.5";
        }
    }

    @JavascriptInterface
    public void log(String msg) {
        Log.d(MainActivity.TAG, "JS: " + msg);
    }

    // ------------------------------------------------------------------
    // Media library
    // ------------------------------------------------------------------

    @JavascriptInterface
    public synchronized String listUploads() {
        try {
            JSONArray out = new JSONArray();
            Set<String> deleted = activity.deletedUploads();

            // bundled demo media (index generated by build.sh)
            String idx = activity.readAssetText("www/bundled-uploads.json");
            if (idx != null) {
                JSONArray arr = new JSONArray(idx);
                for (int i = 0; i < arr.length(); i++) {
                    JSONObject o = arr.getJSONObject(i);
                    if (deleted.contains(o.optString("name"))) continue;
                    out.put(o);
                }
            }

            // user uploads
            File[] files = activity.uploadsDir().listFiles();
            if (files != null) {
                for (File f : files) {
                    if (!f.isFile() || deleted.contains(f.getName())) continue;
                    String ext = extOf(f.getName());
                    if (!isVideo(ext) && !isImage(ext)) continue;
                    JSONObject o = new JSONObject();
                    o.put("name", f.getName());
                    o.put("url", "/uploads/" + f.getName());
                    o.put("size", f.length());
                    o.put("pretty", humanSize(f.length()));
                    o.put("mtime", f.lastModified() / 1000);
                    o.put("video", isVideo(ext));
                    out.put(o);
                }
            }

            // newest first, like server.py list_uploads()
            List<JSONObject> list = new ArrayList<>();
            for (int i = 0; i < out.length(); i++) list.add(out.getJSONObject(i));
            Collections.sort(list, new Comparator<JSONObject>() {
                @Override
                public int compare(JSONObject a, JSONObject b) {
                    return Long.compare(b.optLong("mtime"), a.optLong("mtime"));
                }
            });
            JSONArray sorted = new JSONArray();
            for (JSONObject o : list) sorted.put(o);
            return sorted.toString();
        } catch (Exception e) {
            Log.e(MainActivity.TAG, "listUploads failed", e);
            return "[]";
        }
    }

    @JavascriptInterface
    public synchronized String saveUpload(String name, String mime, String b64) {
        try {
            byte[] data = Base64.decode(b64, Base64.DEFAULT);
            String digest = sha1(data).substring(0, 16);

            String base = name == null ? "" : name.replace('\\', '/');
            base = base.substring(base.lastIndexOf('/') + 1);
            String ext = extOf(base);
            boolean isVideo = isVideo(ext);
            long limit = isVideo ? 300L * 1024 * 1024 : 16L * 1024 * 1024;
            if (data.length > limit) {
                return err("file too large for a " + (isVideo ? "video" : "picture")
                        + " (" + (limit / 1048576) + " MB limit)");
            }
            if (!isVideo && !isImage(ext)) ext = ".png";
            if (ext.isEmpty()) ext = isVideo ? ".mp4" : ".png";

            // identical pictures reuse the existing file (server.py behaviour)
            if (!isVideo) {
                String idx = activity.readAssetText("www/bundled-uploads.json");
                if (idx != null) {
                    JSONArray arr = new JSONArray(idx);
                    for (int i = 0; i < arr.length(); i++) {
                        JSONObject o = arr.getJSONObject(i);
                        if (digest.equals(o.optString("digest"))) {
                            JSONObject res = new JSONObject();
                            res.put("ok", true);
                            res.put("url", o.optString("url"));
                            res.put("size", o.optLong("size"));
                            res.put("reused", true);
                            res.put("files", new JSONArray(listUploads()));
                            return res.toString();
                        }
                    }
                }
                File[] files = activity.uploadsDir().listFiles();
                if (files != null) {
                    for (File f : files) {
                        if (!f.isFile()) continue;
                        String d = sha1(readAll(f));
                        if (digest.equals(d.substring(0, 16))) {
                            JSONObject res = new JSONObject();
                            res.put("ok", true);
                            res.put("url", "/uploads/" + f.getName());
                            res.put("size", f.length());
                            res.put("reused", true);
                            res.put("files", new JSONArray(listUploads()));
                            return res.toString();
                        }
                    }
                }
            }

            String stem = base.contains(".") ? base.substring(0, base.lastIndexOf('.')) : base;
            String safe = stem.replaceAll("[^A-Za-z0-9_-]", "");
            if (safe.length() > 40) safe = safe.substring(0, 40);
            if (safe.isEmpty()) safe = "upload";
            if (safe.matches("\\d{4,6}(-\\d{4,6})?")) {
                safe = new SimpleDateFormat("yyyyMMdd-HHmmss", Locale.US).format(new Date());
            }
            String fname = safe + "-" + digest.substring(0, 6) + ext;
            File out = new File(activity.uploadsDir(), fname);
            FileOutputStream fos = new FileOutputStream(out);
            try {
                fos.write(data);
                fos.flush();
            } finally {
                fos.close();
            }
            JSONObject res = new JSONObject();
            res.put("ok", true);
            res.put("url", "/uploads/" + fname);
            res.put("size", data.length);
            res.put("files", new JSONArray(listUploads()));
            return res.toString();
        } catch (Exception e) {
            Log.e(MainActivity.TAG, "saveUpload failed", e);
            return err("could not read upload: " + e.getMessage());
        }
    }

    @JavascriptInterface
    public synchronized String deleteUpload(String url) {
        try {
            if (url == null || !url.startsWith("/uploads/")) {
                return err("only /uploads/ files can be deleted");
            }
            String name = url.substring("/uploads/".length());
            if (!name.matches("[A-Za-z0-9_.-]+") || name.contains("..")) return err("bad name");
            Set<String> deleted = new HashSet<>(activity.deletedUploads());
            File f = new File(activity.uploadsDir(), name);
            if (f.isFile()) {
                //noinspection ResultOfMethodCallIgnored
                f.delete();
            } else {
                // bundled asset: tombstone it so listing + serving skip it
                deleted.add(name);
            }
            activity.saveDeletedUploads(deleted);
            JSONObject res = new JSONObject();
            res.put("ok", true);
            res.put("files", new JSONArray(listUploads()));
            return res.toString();
        } catch (Exception e) {
            return err(String.valueOf(e.getMessage()));
        }
    }

    // ------------------------------------------------------------------
    // helpers
    // ------------------------------------------------------------------

    private static String err(String msg) {
        try {
            JSONObject o = new JSONObject();
            o.put("ok", false);
            o.put("error", msg);
            return o.toString();
        } catch (Exception e) {
            return "{\"ok\":false}";
        }
    }

    private static String extOf(String name) {
        int i = name.lastIndexOf('.');
        return i >= 0 ? name.substring(i).toLowerCase() : "";
    }

    private static boolean isVideo(String ext) {
        for (String v : VIDEO_EXTS) if (v.equals(ext)) return true;
        return false;
    }

    private static boolean isImage(String ext) {
        for (String v : IMG_EXTS) if (v.equals(ext)) return true;
        return false;
    }

    private static String sha1(byte[] data) {
        try {
            MessageDigest md = MessageDigest.getInstance("SHA-1");
            byte[] h = md.digest(data);
            StringBuilder sb = new StringBuilder();
            for (byte b : h) sb.append(String.format("%02x", b));
            return sb.toString();
        } catch (Exception e) {
            return "";
        }
    }

    private static byte[] readAll(File f) throws Exception {
        FileInputStream in = new FileInputStream(f);
        try {
            java.io.ByteArrayOutputStream out = new java.io.ByteArrayOutputStream();
            byte[] buf = new byte[65536];
            int n;
            while ((n = in.read(buf)) > 0) out.write(buf, 0, n);
            return out.toByteArray();
        } finally {
            in.close();
        }
    }

    private static String humanSize(long n) {
        double v = n;
        if (v < 1024) return v + " B";
        v /= 1024.0;
        if (v < 1024) return String.format(Locale.US, "%.1f KB", v);
        v /= 1024.0;
        return String.format(Locale.US, "%.1f MB", v);
    }

}
